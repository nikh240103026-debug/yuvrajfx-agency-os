
import {
  afterAll,
  beforeAll,
  describe,
  expect,
  it,
} from 'vitest';
import { Db } from '../src/server/db/db.ts';

const connectionString = process.env.TEST_DATABASE_URL;

if (connectionString) {
  const databaseName = new URL(connectionString).pathname.replace(/^\//, '');

  if (databaseName !== 'yuvraj_agency_test') {
    throw new Error(
      'Safety check failed: TEST_DATABASE_URL must target yuvraj_agency_test.',
    );
  }
}

describe.skipIf(!connectionString)('PostgreSQL adapter integration', () => {
  let db: Db;

  beforeAll(() => {
    db = new Db(connectionString!);
  });

  afterAll(async () => {
    if (db) await db.close();
  });

  it('executes queries, inserts, updates, and nested transaction rollback', async () => {
    await db.tx(async () => {
      await db.exec(`
        CREATE TEMP TABLE adapter_probe (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL,
          active BOOLEAN NOT NULL,
          payload JSONB NOT NULL
        ) ON COMMIT DROP
      `);

      const id = await db.insert('adapter_probe', {
        name: 'first',
        active: true,
        payload: { source: 'integration-test' },
      });

      expect(id).toBeGreaterThan(0);

      const inserted = await db.get<{
        name: string;
        active: boolean;
        payload: { source: string };
      }>(
        'SELECT name, active, payload FROM adapter_probe WHERE id = :id',
        { id },
      );

      expect(inserted).toEqual({
        name: 'first',
        active: true,
        payload: { source: 'integration-test' },
      });

      expect(
        await db.update('adapter_probe', id, {
          name: 'updated',
          active: false,
          payload: { source: 'updated-test' },
        }),
      ).toBe(1);

      expect(
        await db.value<number>('SELECT ?::integer AS answer', [42]),
      ).toBe(42);

      await expect(
        await db.tx(async () => {
          await db.insert('adapter_probe', {
            name: 'must-rollback',
            active: true,
            payload: { source: 'nested-transaction' },
          });
          throw new Error('intentional nested rollback');
        }),
      ).rejects.toThrow('intentional nested rollback');

      expect(
        await db.value<number>(
          'SELECT COUNT(*)::integer AS count FROM adapter_probe',
        ),
      ).toBe(1);

    });
  });
});
